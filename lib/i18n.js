export const LANGS = { fa, en };
let current = 'fa';

const get_ = (obj, path) => path.split('.').reduce((o, k) => (o ? o[k] : undefined), obj);

export function t(key, params = {}) {
  let s = get_(LANGS[current], key);
  if (s == null) s = get_(LANGS.en, key);
  if (s == null) return key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

export function getLang() {
  return current;
}

export function setLang(lang) {
  current = LANGS[lang] ? lang : 'fa';
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'fa' ? 'rtl' : 'ltr';
}

/** Farsi-least-surprise number formatting: uses locale digits in FA mode. */
export function fmtNum(n, { persianDigits = true } = {}) {
  if (n == null || Number.isNaN(Number(n))) return t('common.unavailable');
  const num = Number(n);
  if (current === 'fa' && persianDigits) {
    try {
      return new Intl.NumberFormat('fa-IR').format(num);
    } catch {
      return String(num);
    }
  }
  try {
    return new Intl.NumberFormat('en-US').format(num);
  } catch {
    return String(num);
  }
}

export function fmtDateTime(ts) {
  const loc = current === 'fa' ? 'fa-IR' : 'en-GB';
  try {
    return new Intl.DateTimeFormat(loc, { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(ts));
  } catch {
    return new Date(ts).toLocaleString();
  }
}

/** Re-apply all data-i18n* attributes in (sub)tree. */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.dataset.i18nTitle));
  });
}
